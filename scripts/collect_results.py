"""Index of every training run kept for the paper (comparisons, convergence and tuning studies).

    python scripts/collect_results.py

Reads runs/<name>.json (settings + per-design results), runs/<name>.log (fallback for old runs
without json) and runs/<name>_cert.log (physics certificate) and writes
    results/experiments.csv   one row per run, all settings and all error measures
    results/EXPERIMENTS.md    the same as a readable table
Nothing is recomputed; numbers are copied from the run files.  The weights (runs/*.pt), logs and
json files are kept in git, so every run can be re-evaluated later.
"""
import csv
import json
import re
from datetime import datetime
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RUNS, OUT = ROOT / "runs", ROOT / "results"
FINAL = re.compile(r"final test\s*: Ritz N \(upper bound\) vs full GBT: mean ([\d.na]+) %, max ([\d.na]+) %"
                   r"\s*\|\s*head N: mean ([\d.na]+) %, max ([\d.na]+) %")
CERT = re.compile(r"^\s+(head|ritz|s\d+)\s+([\d.]+) % /\s+([\d.]+) %")
KEYS = ["n_train", "val", "bc", "method", "mode", "arch", "R", "k", "width", "depth", "outer", "epochs",
        "steps", "batch", "lr", "lr_final", "ema", "seed", "threads", "gamma", "init", "train", "test"]


def errs(rows, key):
    e = np.array([r[key] / r["N_full"] - 1 for r in rows if np.isfinite(r["N_full"])])
    return e


def one(name):
    row = dict(run=name)
    js, log, cert = RUNS / f"{name}.json", RUNS / f"{name}.log", RUNS / f"{name}_cert.log"
    src = js if js.exists() else log
    row["date"] = datetime.fromtimestamp(src.stat().st_mtime).strftime("%Y-%m-%d %H:%M")
    if js.exists():
        r = json.load(open(js))
        a = r.get("args", {})
        for k in KEYS:
            row[k] = a.get(k, "")
        row["mode"] = a.get("mode", "physics")
        te = r["test"]
        row["n_test"] = len(te)
        h, z = errs(te, "N_head"), errs(te, "N_ritz")
        if len(h):
            row.update(head_mean=100 * np.mean(abs(h)), head_max=100 * np.max(abs(h)), head_bias=100 * np.mean(h),
                       head_above=int(np.sum(h > 0)), ritz_mean=100 * np.mean(abs(z)), ritz_max=100 * np.max(abs(z)))
        ch = r.get("chosen")
        if ch:
            row["chosen"] = f"{ch.get('name')}@{ch.get('it')}"
            row["val_head_mean"] = 100 * ch["val_head"] if ch.get("val_head") is not None else ""
    if log.exists():
        txt = log.read_text(errors="ignore")
        m = FINAL.search(txt)
        if m and "head_mean" not in row:
            row.update(ritz_mean=m[1], ritz_max=m[2], head_mean=m[3], head_max=m[4])
        m = re.search(r"(\d+) training designs", txt)
        if m:
            row["n_used"] = int(m[1])
        t = re.findall(r"\((\d+) s\)", txt)
        if t:
            row["train_time_s"] = int(t[-1])
    if cert.exists():
        for m in map(CERT.match, cert.read_text().splitlines()):
            if m and m[1].startswith("s"):
                row[f"cert{m[1][1:]}_mean"], row[f"cert{m[1][1:]}_max"] = float(m[2]), float(m[3])
    return row


def main():
    names = sorted({p.name.split(".")[0] for p in RUNS.glob("*.log") if not p.name.endswith("_cert.log")}
                   | {p.stem for p in RUNS.glob("*.json") if not p.name.endswith(".flags.json")})
    rows = [one(n) for n in names]
    cols = ["run", "date"] + KEYS + ["n_used", "n_test", "chosen", "val_head_mean", "head_mean", "head_max", "head_bias",
                                     "head_above", "ritz_mean", "ritz_max"]
    cols += sorted({k for r in rows for k in r if k.startswith("cert")}, key=lambda k: (int(re.sub(r"\D", "", k)), k))
    cols += ["train_time_s"]
    OUT.mkdir(exist_ok=True)
    fmt = lambda v: f"{v:.2f}" if isinstance(v, float) else ("" if v is None else str(v))
    with open(OUT / "experiments.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: fmt(r.get(k, "")) for k in cols})
    show = ["run", "date", "bc", "n_used", "val", "method", "mode", "chosen", "head_mean", "head_max", "head_bias",
            "ritz_mean", "cert3_mean", "cert12_mean", "cert12_max", "train_time_s"]
    with open(OUT / "EXPERIMENTS.md", "w") as f:
        f.write("# All training runs (generated by `scripts/collect_results.py`; errors in % vs GBT on the test designs)\n\n"
                "Full settings in `results/experiments.csv`; what each run tested in `docs/RESEARCH_LOG.md`.\n\n")
        f.write("| " + " | ".join(show) + " |\n|" + "---|" * len(show) + "\n")
        for r in rows:
            f.write("| " + " | ".join(fmt(r.get(k, "")) for k in show) + " |\n")
    print(f"{len(rows)} runs -> results/experiments.csv, results/EXPERIMENTS.md")


if __name__ == "__main__":
    main()
